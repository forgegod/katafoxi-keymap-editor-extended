const ALIASES: Record<string, string> = {
  times: 'times-circle',
  'xmark-circle': 'times-circle',
  refresh: 'sync',
  rotate: 'sync'
}

export function resolveIcon(name: string, collection?: string): IconDef | null {
  if (name === 'github' || (collection === 'brands' && name === 'github')) {
    return GITHUB
  }
  const key = ALIASES[name] ?? name
  const paths = SOLID[key]
  if (!paths) return null
  return { viewBox: '0 0 512 512', paths }
}
