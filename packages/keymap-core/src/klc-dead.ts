/**
 * Dead-key composition tables for .klc export.
 *
 * One entry per X11 `dead_*` name. `id` is the spacing character MSKLC
 * writes on the DEADKEY line. `pairs` map a following character to the
 * composed result. A new accent is another entry here; a locale that
 * uses a different spacing character for the same accent overrides `id`
 * without copying the pairs.
 */

export interface WindowsDeadKey {
  readonly keysym: string
  readonly id: number
  readonly pairs: readonly (readonly [number, number])[]
}

